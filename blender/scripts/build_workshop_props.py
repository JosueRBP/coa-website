def stats(cols):
    for name,col in cols.items():
        meshes=[o for o in col.all_objects if o.type=="MESH"]
        polys=sum(len(o.data.polygons) for o in meshes)
        tris=sum(max(1,len(p.vertices)-2) for o in meshes for p in o.data.polygons)
        curves=sum(o.type=="CURVE" for o in col.all_objects)
        est=tris*3*40/(1024*1024)*0.28
        print(f"PN_PROP_STATS {name} objects={len(col.all_objects)} meshes={len(meshes)} curves={curves} polygons={polys} triangles_mesh_only={tris} estimated_GLBGzip_MB={est:.3f}")


