def refine_approved_wood():
    names=("MAT_Walnut_Provisional","MAT_Walnut_Dark","MAT_Walnut_Drawer_A",
           "MAT_Walnut_Drawer_B","MAT_Walnut_Frame")
    for name in names:
        material=bpy.data.materials.get(name)
        if not material or not material.use_nodes: continue
        nodes=material.node_tree.nodes; links=material.node_tree.links
        bsdf=nodes.get("Principled BSDF")
        if not bsdf: continue
        socket=bsdf.inputs["Base Color"]
        if socket.links:
            old=socket.links[0]; source=old.from_socket; links.remove(old)
            hue=nodes.new("ShaderNodeHueSaturation"); hue.inputs["Saturation"].default_value=0.62; hue.inputs["Value"].default_value=0.76
            links.new(source,hue.inputs["Color"]); links.new(hue.outputs["Color"],socket)
        for node in nodes:
            if node.bl_idname=="ShaderNodeMapRange":
                node.inputs["To Min"].default_value=max(0.46,node.inputs["To Min"].default_value)
                node.inputs["To Max"].default_value=max(0.64,node.inputs["To Max"].default_value)


