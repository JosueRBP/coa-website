def collection(name):
    col = bpy.data.collections.new(name)
    bpy.context.scene.collection.children.link(col)
    return col


def mat(name, color, rough=0.5, metallic=0.0, transmission=0.0, alpha=1.0):
    m = bpy.data.materials.new(name)
    m.diffuse_color = (*color, alpha)
    m.use_nodes = True
    bsdf = m.node_tree.nodes.get("Principled BSDF")
    bsdf.inputs["Base Color"].default_value = (*color, 1)
    bsdf.inputs["Roughness"].default_value = rough
    bsdf.inputs["Metallic"].default_value = metallic
    bsdf.inputs["IOR"].default_value = 1.46
    if transmission:
        bsdf.inputs["Transmission Weight"].default_value = transmission
    if alpha < 1:
        bsdf.inputs["Alpha"].default_value = alpha
    return m


def box(name, loc, dims, material, col, bevel=0.01, parent=None):
    bpy.ops.mesh.primitive_cube_add(location=loc)
    o = bpy.context.object
    o.name = name
    o.dimensions = dims
    bpy.ops.object.transform_apply(location=False, rotation=False, scale=True)
    if bevel:
        mod = o.modifiers.new("EdgeWear", "BEVEL")
        mod.width = bevel
        mod.segments = 2
    o.data.materials.append(material)
    move(o, col)
    if parent:
        o.parent = parent
        o.matrix_parent_inverse = parent.matrix_world.inverted()
    return o


def cylinder(name, loc, radius, depth, material, col, vertices=24, rotation=None, parent=None):
    bpy.ops.mesh.primitive_cylinder_add(vertices=vertices, radius=radius, depth=depth, location=loc,
                                       rotation=rotation or (0,0,0))
    o = bpy.context.object
    o.name = name
    o.data.materials.append(material)
    move(o, col)
    if parent:
        o.parent = parent
        o.matrix_parent_inverse = parent.matrix_world.inverted()
    return o


def move(obj, col):
    for c in list(obj.users_collection):
        c.objects.unlink(obj)
    col.objects.link(obj)


def tube(name, points, radius, material, col, cyclic=False, parent=None, resolution=1):
    curve = bpy.data.curves.new(name+"_Curve", "CURVE")
    curve.dimensions = "3D"
    curve.resolution_u = resolution
    curve.bevel_depth = radius
    curve.bevel_resolution = 2
    spl = curve.splines.new("POLY")
    spl.points.add(len(points)-1)
    for p, co in zip(spl.points, points):
        p.co = (*co,1)
    spl.use_cyclic_u = cyclic
    o = bpy.data.objects.new(name, curve)
    col.objects.link(o)
    o.data.materials.append(material)
    if parent:
        o.parent = parent
        o.matrix_parent_inverse = parent.matrix_world.inverted()
    return o


def rounded_rect_points(cx, cz, width, height, radius, segments=5):
    pts=[]
    corners=((cx+width/2-radius,cz+height/2-radius,0),
             (cx-width/2+radius,cz+height/2-radius,1),
             (cx-width/2+radius,cz-height/2+radius,2),
             (cx+width/2-radius,cz-height/2+radius,3))
    ranges=((0,math.pi/2),(math.pi/2,math.pi),(math.pi,3*math.pi/2),(3*math.pi/2,math.tau))
    for (x,z,_),(a0,a1) in zip(corners,ranges):
        for i in range(segments):
            a=a0+(a1-a0)*i/(segments-1)
            pts.append((x+radius*math.cos(a),z+radius*math.sin(a)))
    return pts


def rounded_ring(name, cx, width, height, corner, rim, depth, material, col, root):
    outer=rounded_rect_points(cx,0,width,height,corner,6)
    inner=rounded_rect_points(cx,0,width-2*rim,height-2*rim,max(0.018,corner-rim),6)
    n=len(outer); verts=[]
    for y in (-depth/2,depth/2):
        verts += [(x,y,z) for x,z in outer] + [(x,y,z) for x,z in inner]
    faces=[]
    # Front/back annular faces and outer/inner depth walls.
    for i in range(n):
        j=(i+1)%n
        faces += [(i,j,n+j,n+i), (2*n+i,3*n+i,3*n+j,2*n+j),
                  (i,2*n+i,2*n+j,j), (n+i,n+j,3*n+j,3*n+i)]
    mesh=bpy.data.meshes.new(name+"_Mesh"); mesh.from_pydata(verts,[],faces); mesh.update()
    obj=bpy.data.objects.new(name,mesh); col.objects.link(obj); obj.data.materials.append(material); obj.parent=root
    bevel=obj.modifiers.new("AcetateEdgeBevel","BEVEL"); bevel.width=0.006; bevel.segments=2
    return obj


def rounded_lens(name,cx,width,height,corner,material,col,root):
    pts=rounded_rect_points(cx,0,width,height,corner,6)
    verts=[(x,0.018,z) for x,z in pts]
    mesh=bpy.data.meshes.new(name+"_Mesh"); mesh.from_pydata(verts,[],[tuple(range(len(verts)))]); mesh.update()
    obj=bpy.data.objects.new(name,mesh); col.objects.link(obj); obj.data.materials.append(material); obj.parent=root
    solid=obj.modifiers.new("LensThickness","SOLIDIFY"); solid.thickness=0.006
    bevel=obj.modifiers.new("LensEdge","BEVEL"); bevel.width=0.003; bevel.segments=2
    return obj


def create_eyewear(name, location, acetate, clear, col, style=0, scale=1.0):
    root = bpy.data.objects.new(name, None)
    root.empty_display_type = "CUBE"
    root.empty_display_size = 0.12
    root.location = location
    root["product_id"] = name
    root["raycast_root"] = True
    root["future_animation_root"] = True
    col.objects.link(root)
    width=(0.285+0.012*(style%3))*scale
    height=(0.205+0.010*((style+1)%3))*scale
    center=(0.176+0.008*(style%2))*scale
    corner=(0.052+0.006*(style%3))*scale
    rim=(0.030+0.003*((style+1)%3))*scale
    depth=(0.040+0.004*(style%2))*scale
    for side,cx in (("L",-center),("R",center)):
        rounded_ring(f"{name}_Front_{side}",cx,width,height,corner,rim,depth,acetate,col,root)
        rounded_lens(f"{name}_Lens_{side}",cx,width-2*rim-0.008,height-2*rim-0.008,
                     max(0.015,corner-rim),clear,col,root)
        # Recognizable hinge block at the outer corner.
        hx=cx+(-1 if side=="L" else 1)*(width/2-0.006)
        h=box(f"{name}_Hinge_{side}",(location[0]+hx,location[1]-0.004,location[2]+0.006),
              (0.025,0.052,0.052),bpy.data.materials["MAT_Prop_AgedBrass"],col,0.005,root)
    bridge_z=0.018+0.008*(style%2)
    bridge_gap=2*center-width
    box(f"{name}_Bridge",(location[0],location[1],location[2]+bridge_z),
        (bridge_gap+0.045,depth,0.045),acetate,col,0.010,root)
    # Patillas recede onto the shelf instead of reading as flat whiskers.
    for side,sgn in (("L",-1),("R",1)):
        x=sgn*(center+width/2)
        tube(f"{name}_Temple_{side}",[(x,0,0.005),(x+sgn*0.09,0.08,-0.015),(x+sgn*0.12,0.26,-0.045)],
             0.010*scale,acetate,col,False,root)
    return root


